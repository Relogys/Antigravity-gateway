/** Minimal prompt surface so the wizard can be driven by tests or other UIs. */
export interface WizardPrompter {
  ask(question: string, defaultValue?: string): Promise<string>;
  confirm(question: string, defaultYes?: boolean): Promise<boolean>;
  print(line: string): void;
}

export interface SetupWizardOptions {
  cwd?: string;
  prompter?: WizardPrompter;
  envPath?: string;
  nonInteractive?: boolean;
  presetChannels?: string[];
}

export interface SetupWizardResult {
  envPath: string;
  channels: string[];
  values: Record<string, string>;
  wrote: boolean;
}

export interface ParsedEnvFile {
  /** Original lines with CRLF normalized and the single trailing newline removed. */
  lines: string[];
  /** Last value wins for duplicate keys. */
  values: Record<string, string>;
}

const FRESH_ENV_HEADER = [
  "# Antigravity Gateway configuration",
  "# Generated by `pnpm setup`. Re-running setup keeps existing values.",
  "",
].join("\n");

const AGY_INSTALL_URL = "https://antigravity.google/docs/getting-started";
const SECRET_KEY_RE = /(TOKEN|SECRET|PASSWORD|API_?KEY|ACCESS_KEY|PRIVATE_KEY)/i;

export function isSecretEnvKey(key: string): boolean {
  if (/ALLOWED/i.test(key)) {
    return false;
  }
  return SECRET_KEY_RE.test(key);
}

function parseDoubleQuoted(raw: string): string {
  let out = "";
  for (let i = 1; i < raw.length; i += 1) {
    const char = raw[i]!;
    if (char === '"') {
      return out;
    }
    if (char === "\\") {
      const next = raw[i + 1];
      if (next === undefined) {
        break;
      }
      if (next === "n") out += "\n";
      else if (next === "r") out += "\r";
      else if (next === "t") out += "\t";
      else out += next;
      i += 1;
      continue;
    }
    out += char;
  }
  return out;
}

function parseSingleQuoted(raw: string): string {
  let out = "";
  for (let i = 1; i < raw.length; i += 1) {
    const char = raw[i]!;
    if (char === "'") {
      return out;
    }
    out += char;
  }
  return out;
}

function parseEnvLine(line: string): { key: string; value: string } | null {
  const match = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
  if (!match) {
    return null;
  }
  const key = match[1]!;
  const rest = match[2] ?? "";
  if (rest.startsWith('"')) {
    return { key, value: parseDoubleQuoted(rest) };
  }
  if (rest.startsWith("'")) {
    return { key, value: parseSingleQuoted(rest) };
  }
  const commentIdx = rest.search(/\s#/);
  const unquoted = commentIdx === -1 ? rest : rest.slice(0, commentIdx);
  return { key, value: unquoted.trim() };
}

/** Safe key=value parser that preserves every raw line (comments, exports, blank lines). */
export function parseEnvFile(content: string): ParsedEnvFile {
  const normalized = content.replace(/\r\n?/g, "\n");
  const lines = normalized.length === 0 ? [] : normalized.split("\n");
  if (lines.length > 0 && lines[lines.length - 1] === "") {
    lines.pop();
  }
  const values: Record<string, string> = {};
  for (const line of lines) {
    const entry = parseEnvLine(line);
    if (entry) {
      values[entry.key] = entry.value;
    }
  }
  return { lines, values };
}

function encodeEnvValue(value: string): string {
  if (value === "") {
    return "";
  }
  if (/^[A-Za-z0-9_./:@+,\-=]+$/.test(value)) {
    return value;
  }
  const escaped = value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n");
  return `"${escaped}"`;
}

/**
 * Apply updates to a parsed `.env` while leaving unmanaged lines untouched.
 * `undefined` removes a key; new keys are appended in update order.
 */
export function serializeEnvUpdates(
  existing: ParsedEnvFile | string,
  updates: Record<string, string | undefined>,
): string {
  const parsed = typeof existing === "string" ? parseEnvFile(existing) : existing;
  const pending = new Map(Object.entries(updates));
  const seen = new Set<string>();
  const out: string[] = [];

  for (const line of parsed.lines) {
    const entry = parseEnvLine(line);
    if (!entry || !pending.has(entry.key)) {
      out.push(line);
      continue;
    }
    if (seen.has(entry.key)) {
      continue;
    }
    seen.add(entry.key);
    const value = pending.get(entry.key);
    pending.delete(entry.key);
    if (value !== undefined) {
      out.push(`${entry.key}=${encodeEnvValue(value)}`);
    }
  }

  const appended: string[] = [];
  for (const [key, value] of pending) {
    if (value !== undefined) {
      appended.push(`${key}=${encodeEnvValue(value)}`);
    }
  }
  if (appended.length > 0) {
    if (out.length > 0 && out[out.length - 1]!.trim() !== "") {
      out.push("");
    }
    out.push(...appended);
  }

  while (out.length > 0 && out[out.length - 1]!.trim() === "") {
    out.pop();
  }
  return out.length === 0 ? "" : `${out.join("\n")}\n`;
}

