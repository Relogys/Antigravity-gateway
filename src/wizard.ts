const APPROVAL_MODES = ["interactive", "auto", "sandbox"] as const;

function parseBoolLike(value: string | undefined, fallback: boolean): boolean {
  if (value === undefined || value.trim() === "") {
    return fallback;
  }
  const normalized = value.trim().toLowerCase();
  if (["1", "true", "yes", "on"].includes(normalized)) return true;
  if (["0", "false", "no", "off"].includes(normalized)) return false;
  return fallback;
}

function resolveChannelSelection(raw: string): ChannelDefinition[] {
  const tokens = raw
    .split(/[\s,]+/)
    .map((token) => token.trim().toLowerCase())
    .filter(Boolean);
  const picked = new Map<number, ChannelDefinition>();
  for (const token of tokens) {
    const match =
      CHANNELS.find((channel) => String(channel.id) === token) ??
      CHANNELS.find((channel) => channel.name === token);
    if (match) {
      picked.set(match.id, match);
    }
  }
  return [...picked.values()].sort((a, b) => a.id - b.id);
}

async function promptFieldValue(
  prompter: WizardPrompter,
  field: ChannelField,
  values: Record<string, string>,
  nonInteractive: boolean,
): Promise<string | undefined> {
  const existing = values[field.key];
  const hasExisting = existing !== undefined && existing !== "";

  if (nonInteractive) {
    if (hasExisting) return existing;
    if (field.generate) return field.generate();
    return field.defaultValue;
  }

  const secret = isSecretEnvKey(field.key);
  const masked = hasExisting && secret;
  let prompt = field.label;
  if (!hasExisting && field.optional && !field.generate) {
    prompt += " (optional, Enter to skip)";
  }
  const suffix = masked ? " [already set — Enter to keep]" : "";
  const defaultValue = hasExisting && !secret ? existing : (field.defaultValue ?? "");

  const answer = (await prompter.ask(`${prompt}${suffix}`, defaultValue)).trim();
  if (answer === "") {
    if (hasExisting) return existing;
    if (field.generate) return field.generate();
    return field.defaultValue;
  }
  return answer;
}

function applyDefaults(
  updates: Record<string, string | undefined>,
  values: Record<string, string>,
  constants: Record<string, string> | undefined,
): void {
  for (const [key, value] of Object.entries(constants ?? {})) {
    const existing = updates[key] ?? values[key];
    if (existing === undefined || existing === "") {
      updates[key] = value;
    }
  }
}

async function commandAvailable(bin: string): Promise<boolean> {
  return new Promise((resolve) => {
    let settled = false;
    let timer: NodeJS.Timeout | undefined;
    const finish = (ok: boolean) => {
      if (settled) return;
      settled = true;
      if (timer) clearTimeout(timer);
      resolve(ok);
    };
    try {
      const child = spawn(bin, ["--version"], { stdio: "ignore", windowsHide: true });
      child.once("error", () => finish(false));
      child.once("exit", (code) => finish(code === 0));
      timer = setTimeout(() => {
        child.kill();
        finish(false);
      }, 3000);
    } catch {
      finish(false);
    }
  });
}

function createReadlinePrompter(): { prompter: WizardPrompter; close: () => void } {
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  return {
    prompter: {
      async ask(question, defaultValue) {
        const suffix =
          defaultValue !== undefined && defaultValue !== "" ? ` [${defaultValue}]` : "";
        const answer = await rl.question(`${question}${suffix}: `);
        return answer.trim();
      },
      async confirm(question, defaultYes = false) {
        const hint = defaultYes ? "[Y/n]" : "[y/N]";
        const answer = (await rl.question(`${question} ${hint}: `)).trim().toLowerCase();
        if (answer === "") return defaultYes;
        return ["y", "yes", "true", "1"].includes(answer);
      },
      print(line) {
        console.log(line);
      },
    },
    close: () => rl.close(),
  };
}

/**
 * Interactive first-time setup. Safe to re-run: existing secrets and unrelated
 * `.env` keys are preserved when the user presses Enter.
 */
export async function runSetupWizard(options: SetupWizardOptions = {}): Promise<SetupWizardResult> {
  const cwd = path.resolve(options.cwd ?? process.cwd());
  const envPath = path.resolve(options.envPath ?? path.join(cwd, ".env"));
  const nonInteractive = options.nonInteractive === true;
  const usingDefaultPrompter = !options.prompter;
  const owned = usingDefaultPrompter ? createReadlinePrompter() : null;
  const prompter = options.prompter ?? owned!.prompter;

  try {
    let existingContent = "";
    let exists = false;
    try {
      existingContent = await readFile(envPath, "utf8");
      exists = true;
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== "ENOENT") {
        throw err;
      }
    }

    const parsed = parseEnvFile(exists ? existingContent : FRESH_ENV_HEADER);
    const values = { ...parsed.values };
    const updates: Record<string, string | undefined> = {};

    prompter.print("Antigravity Gateway — first-time setup");
    prompter.print("======================================");
    prompter.print("");
    prompter.print("Step 1/4 — Environment check");
    const nodeMajor = Number.parseInt(process.versions.node.split(".")[0] ?? "0", 10);
    if (nodeMajor >= 22) {
      prompter.print(`  [OK] Node.js ${process.version}`);
    } else {
      prompter.print(
        `  [WARN] Node.js ${process.version} is below the required >=22.0.0 (https://nodejs.org/en/download)`,
      );
    }
    if (!nonInteractive && usingDefaultPrompter) {
      const agyBin = process.env.AGY_BIN?.trim() || "agy";
      if (await commandAvailable(agyBin)) {
        prompter.print(`  [OK] Found '${agyBin}' on PATH`);
      } else {
        prompter.print(
          `  [WARN] '${agyBin}' was not found on PATH — install the Antigravity CLI: ${AGY_INSTALL_URL}`,
        );
        prompter.print("         (continuing; configure it before 'pnpm cli start')");
      }
    }
    prompter.print("");

    prompter.print("Step 2/4 — Choose channels");
    let selectedDefs: ChannelDefinition[];
    if (options.presetChannels && options.presetChannels.length > 0) {
      selectedDefs = resolveChannelSelection(options.presetChannels.join(","));
      if (selectedDefs.length === 0) {
        prompter.print(
          `  [WARN] No known channels in preset "${options.presetChannels.join(",")}"; skipping channel setup.`,
        );
      }
    } else if (nonInteractive) {
      selectedDefs = [];
    } else {
      for (const channel of CHANNELS) {
        prompter.print(`  ${channel.id}) ${channel.label.padEnd(22)} ${channel.hint}`);
      }
      const selection = await prompter.ask(
        "Select channels (comma-separated, e.g. 1,2)",
        "1",
      );
      selectedDefs = resolveChannelSelection(selection);
      if (selectedDefs.length === 0) {
        prompter.print("  [WARN] No valid channels selected; skipping channel setup.");
      }
    }

    const selected: string[] = [];
    for (const channel of selectedDefs) {
      prompter.print("");
      prompter.print(`Configuring ${channel.label}...`);
      const missing: string[] = [];
      for (const field of channel.fields) {
        const value = await promptFieldValue(prompter, field, values, nonInteractive);
        if (value === undefined || value === "") {
          if (!field.optional) {
            missing.push(field.key);
          }
          continue;
        }
        updates[field.key] = value;
      }
      applyDefaults(updates, values, channel.constants);
      if (missing.length > 0) {
        prompter.print(
          `  [WARN] ${channel.label}: missing ${missing.join(", ")} — this channel stays disabled until set.`,
        );
      } else {
        selected.push(channel.name);
      }
    }
    if (selected.length > 0) {
      prompter.print("");
      prompter.print(`Selected: ${selected.join(", ")}`);
    }
    prompter.print("");

    prompter.print("Step 3/4 — Access control & safety");
    const allowedSenders = await promptFieldValue(
      prompter,
      {
        key: "ALLOWED_SENDERS",
        label: "Allowed sender IDs (comma-separated; blank = safe pairing-code mode)",
        optional: true,
      },
      values,
      nonInteractive,
    );
    if (allowedSenders !== undefined && allowedSenders !== "") {
      updates.ALLOWED_SENDERS = allowedSenders;
    }

    const approvalAnswer = await promptFieldValue(
      prompter,
      {
        key: "APPROVAL_MODE",
        label: "Tool approval mode (interactive / auto / sandbox)",
        defaultValue: "interactive",
      },
      values,
      nonInteractive,
    );
    let approvalMode = (approvalAnswer ?? "interactive").toLowerCase();
    if (!(APPROVAL_MODES as readonly string[]).includes(approvalMode)) {
      prompter.print(`  [WARN] Unknown approval mode "${approvalAnswer}"; using "interactive".`);
      approvalMode = "interactive";
    }
    updates.APPROVAL_MODE = approvalMode;

    const defaultHealth = parseBoolLike(values.HEALTH_ENABLED, true);
    const healthEnabled = nonInteractive
      ? defaultHealth
      : await prompter.confirm(
          "Enable the local health endpoint on 127.0.0.1:18790? (recommended; powers 'pnpm cli status')",
          defaultHealth,
        );
    updates.HEALTH_ENABLED = healthEnabled ? "true" : "false";
    if (healthEnabled) {
      if (values.HEALTH_HOST === undefined || values.HEALTH_HOST === "") {
        updates.HEALTH_HOST = "127.0.0.1";
      }
      if (values.HEALTH_PORT === undefined || values.HEALTH_PORT === "") {
        updates.HEALTH_PORT = "18790";
      }
    }
    prompter.print("");

    prompter.print("Step 4/4 — Write configuration");
    const content = serializeEnvUpdates(parsed, updates);
    const wrote = !exists || content !== existingContent;
    if (wrote) {
      await mkdir(path.dirname(envPath), { recursive: true });
      await writeFile(envPath, content, { encoding: "utf8", mode: 0o600 });
      try {
        await chmod(envPath, 0o600);
      } catch {
        // Windows and some filesystems ignore POSIX modes; best effort only.
      }
    }
    prompter.print(`  [OK] ${wrote ? "Wrote" : "Kept"} ${envPath}`);
    prompter.print("");
    prompter.print("Next steps:");
    prompter.print("  1. pnpm build          # compile the gateway");
    prompter.print("  2. pnpm cli doctor     # verify configuration and connectivity");
    prompter.print("  3. pnpm cli start      # launch in the background");
    prompter.print("");
    prompter.print("Then send '/help' to your bot from an approved account.");
    prompter.print("Follow logs with: pnpm cli logs");

    return {
      envPath,
      channels: selected,
      values: parseEnvFile(content).values,
      wrote,
    };
  } finally {
    owned?.close();
  }
}